"""Write docs/permissions.md: the role each route requires, read from the code (app/web/route_audit.py).

  python tools/permissions_report.py

The same table is checked by tests/api/test_permissions_matrix.py, which also
requests every route as every role that should be refused.
"""
from __future__ import annotations

import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

HEAD = """# Permissions audit

Generated by `python tools/permissions_report.py` from the code itself; don't edit by hand. Every route either
depends on a server-side role check or is listed as public with a reason. `tests/api/test_permissions_matrix.py`
fails if a route has neither, requests every route as every role that should be refused (anonymous, student,
staff, coordinator) and checks it is refused without changing any data, and checks that signed-in users can't
reach other classes' committees, live sessions, debates or students.

**Roles.** *Coordinator*: everything. *Staff*: their own classes plus school-wide debating events; never admin,
staff accounts, data switch or restore, AI settings, licence confirmation or student erasure. *Student*: their own
class, delegation and records. *Signed in*: anyone signed in, with a per-item check inside the route (for example a
student may open a resolution only in their own class's committee, and a ballot only for a debate they adjudicate).
*Public*: no sign-in; see the reason.

**Checks inside routes, beyond the role** (tested in `test_scope_other_class` and the phase test files):
- staff only reach classes they are assigned to (`can_run_class`), and committees, sessions and class debating events
  of those classes; class archiving, unarchiving and student erasure are coordinator-only inside `/people`;
- students only reach their own class's live session (and the 25-student cap applies), committees where their
  delegation sits, debates they are in or adjudicate, and their own practice, AI practice and pathway;
- the WebSocket checks every channel subscription the same way (`app/web/ws.py`, `channel_allowed`);
- projector pages need the session's or event's random token and show public information only.

"""


def main() -> str:
    from app.config import Settings
    from app.main import create_app
    from app.util import hash_passphrase
    from app.web.route_audit import LEVELS, classify
    tmp = Path(tempfile.mkdtemp(prefix="soc-perm-"))
    s = Settings(data_dir=tmp).load()
    s.values["coordinator_hash"] = hash_passphrase("report only")
    s.save()
    table = classify(create_app(s))
    by_level = defaultdict(list)
    for r in table:
        by_level[r["level"]].append(r)
    names = {"public": "Public", "signed_in": "Signed in (any role, checked per item)", "student": "Students only",
             "staff": "Staff and coordinator", "coordinator": "Coordinator only", "UNCHECKED": "UNCHECKED — must be fixed"}
    out = [HEAD, "| Role required | Routes |", "|---|---|"]
    for lvl in LEVELS + ["UNCHECKED"]:
        if by_level[lvl]:
            out.append(f"| {names[lvl]} | {len(by_level[lvl])} |")
    out.append(f"| **Total** | **{len(table)}** |\n")
    for lvl in reversed(LEVELS + ["UNCHECKED"]):
        if not by_level[lvl]:
            continue
        out.append(f"## {names[lvl]}\n")
        out.append("| Method | Path |" + (" Why public |" if lvl == "public" else ""))
        out.append("|---|---|" + ("---|" if lvl == "public" else ""))
        for r in by_level[lvl]:
            out.append(f"| {r['method']} | `{r['path']}` |" + (f" {r['note']} |" if lvl == "public" else ""))
        out.append("")
    text = "\n".join(out)
    (ROOT / "docs" / "permissions.md").write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    t = main()
    print(t.split("## ")[0][-400:])
