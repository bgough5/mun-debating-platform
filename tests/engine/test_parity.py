"""Parity: the Python port reproduces the frozen v2 JavaScript exactly (spec §5.8).

Fixture generated by `node tools/parity/gen_fixture.js` from shared/engine.js
and src/pack_climate2026.js.
"""
import json
from pathlib import Path

import pytest

from app.engine import sponsorship
from app.engine.priors.archetype import apply_tag_amendment, stance_of

ROOT = Path(__file__).resolve().parents[2]
FIX = json.loads((ROOT / "tests/fixtures/stance_parity.json").read_text(encoding="utf-8"))
PACK = json.loads((ROOT / "app/db/seed/legacy_pack_climate2026.json").read_text(encoding="utf-8"))
COUNTRIES = {c["n"]: c for c in PACK["countries"]}
AFF = {k: v["affinity"] for k, v in PACK["archetypes"].items()}
CLAUSES = {c["id"]: c for c in PACK["clauses"]}
AMENDMENTS = {a["id"]: a for a in PACK["amendments"]}


def test_fixture_sizes():
    assert len(FIX["cells"]) == 279
    assert len(FIX["amendment_cases"]) == 54


def _override(country, clause_id):
    o = PACK["overrides"].get(f"{country}|{clause_id}") if clause_id else None
    return (o["s"], o["line"]) if o else None


def test_all_279_cells_match():
    mismatches = []
    for cell in FIX["cells"]:
        c = COUNTRIES[cell["country"]]
        st = stance_of(c["w"], cell["tags"], AFF, _override(cell["country"], cell["clause"]))
        if st.s != cell["s"] or st.forced != cell["forced"] or st.raw != cell["raw"]:
            mismatches.append((cell["country"], cell["clause"], st, cell))
    assert mismatches == []


def test_all_54_amendment_cases_match():
    mismatches = []
    for case in FIX["amendment_cases"]:
        a = AMENDMENTS[case["amendment"]]
        tags = apply_tag_amendment(CLAUSES[case["clause"]]["tags"], a["add"], a["remove"])
        assert tags == case["tags"]
        yes = no = ab = 0
        for row in case["stances"]:
            st = stance_of(COUNTRIES[row["country"]]["w"], tags, AFF, None)
            if st.s != row["s"] or st.raw != row["raw"]:
                mismatches.append((case["clause"], case["amendment"], row["country"]))
            yes += st.s > 0
            no += st.s < 0
            ab += st.s == 0
        assert (yes, ab, no, yes > no) == (case["yes"], case["abstain"], case["no"], case["passed"])
    assert mismatches == []


@pytest.mark.parametrize("i", range(300))
def test_sponsorship_matches_js(i):
    case = FIX["sponsorship_cases"][i]
    events = [{"seq": e["seq"], "player": e["playerId"], "kind": e["kind"], "payload": e["payload"]}
              for e in case["events"]]
    assert sponsorship.resolve(events, "amendment_sponsor", "amendment_second", "amendmentId") == case["winner"]


def test_empty_tags_abstain():
    st = stance_of(COUNTRIES["Australia"]["w"], [], AFF)
    assert st.s == 0 and st.raw is None
